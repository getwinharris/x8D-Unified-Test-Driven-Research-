import test from 'node:test';
import assert from 'node:assert/strict';
import {
  exportCompactX8dArtifact,
  loadAndEvalFromCompactX8dBinary,
  runNativeCompactTrainingExperiment,
} from './nativeCompactTrainEngine';

test('From-scratch Compact Native .x8D trains in factored STE space, beats FP16 size >30x, and generates from reloaded binary bytes alone', () => {
  const report = runNativeCompactTrainingExperiment({
    epochs: 36,
    kTerms: 4,
    factorBits: 4,
    seed: 20261117,
  });

  // 1. Random initialization check (prior to gradient descent, PPL is ~256 over 256 raw byte states)
  assert.ok(report.denseReference.initHeldOutPpl > 150);
  assert.ok(report.compactNativeX8d.initHeldOutPpl > 150);

  // 2. Real optimization drop on training & unseen held-out split
  assert.ok(
    report.denseReference.finalHeldOutPpl < 3.5,
    `Expected dense held-out PPL < 3.5, got ${report.denseReference.finalHeldOutPpl}`
  );
  assert.ok(
    report.compactNativeX8d.finalHeldOutPpl < 4.0,
    `Expected compact native held-out PPL < 4.0, got ${report.compactNativeX8d.finalHeldOutPpl}`
  );
  assert.ok(report.compactNativeX8d.heldOutTop1AccPct >= 70);

  // 3. Real serialized .x8D artifact compression & zero hidden dense buffers
  assert.ok(report.compactNativeX8d.trainableDofs < report.compactNativeX8d.effectiveWeights / 5);
  assert.ok(report.compactNativeX8d.serializedBytes < 1600);
  assert.ok(report.compactNativeX8d.compressionVsFp16 > 30);
  assert.ok(report.compactNativeX8d.activeEvalBufferBytes < report.denseReference.activeEvalBufferBytes / 5);

  // 4. Reload strictly from binary Uint8Array preserves logits cleanly & generates coherent bytes
  assert.ok(report.compactNativeX8d.reloadExactParityMaxDiff < 1e-4);
  assert.ok(
    report.compactNativeX8d.generatedContinuation.includes('pick') ||
      report.compactNativeX8d.generatedContinuation.includes('task'),
    `Expected coherent generated bytes from reloaded .x8D, got ${JSON.stringify(report.compactNativeX8d.generatedContinuation)}`
  );
  assert.equal(report.compactNativeX8d.generatedQuantaSample.length, 8);
});

test('Ultra-compact K=2, 2-bit native .x8D training drops below 600 bytes (<0.20 bpw measured) while still reducing held-out perplexity', () => {
  const report = runNativeCompactTrainingExperiment({
    epochs: 36,
    kTerms: 2,
    factorBits: 2,
    seed: 20261117,
  });

  assert.ok(
    report.compactNativeX8d.serializedBytes < 650,
    `Expected <650 B binary .x8D for K=2 2-bit, got ${report.compactNativeX8d.serializedBytes}`
  );
  assert.ok(
    report.compactNativeX8d.achievedBpw < 0.22,
    `Expected <0.22 bpw on tiny 24.8K toy model, got ${report.compactNativeX8d.achievedBpw}`
  );
  assert.ok(
    report.compactNativeX8d.finalHeldOutPpl < report.compactNativeX8d.initHeldOutPpl * 0.25,
    `Expected sharp PPL drop from ${report.compactNativeX8d.initHeldOutPpl}, got ${report.compactNativeX8d.finalHeldOutPpl}`
  );
  assert.ok(typeof exportCompactX8dArtifact === 'function' && typeof loadAndEvalFromCompactX8dBinary === 'function');
});
